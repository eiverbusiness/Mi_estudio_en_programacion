let numero = 8;
let numeroDia = "";

switch(numero)
{
    case 1:
        numeroDia = "Lunes";
        console.log(numeroDia);
        break;
    case 2 :
        numeroDia = "Martes";
        console.log(numeroDia);
        break;
    case 3:
        numeroDia = "Miercoles";
        console.log(numeroDia);
        break;
    case 4:
        numeroDia = "Jueves";
        console.log(numeroDia);
        break;
    case 5:
        numeroDia = "Viernes";
        console.log(numeroDia);
        break;
    case 6:
        numeroDia = "Sabado";
        console.log(numeroDia);
        break;
    case 7:
        numeroDia = "Domingo";
        console.log(numeroDia);
        break;
    default:
        console.log('Numero invalido, elije uno de el 1 al 7.');
}